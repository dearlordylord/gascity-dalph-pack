import {chromium} from 'playwright';
import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const fixture=JSON.parse(readFileSync(new URL('./fixtures/fork-join.json',import.meta.url)));
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1600,height:1000}});const errors=[];page.on('pageerror',e=>errors.push(e.message));
let failed=false;
await page.route('**/api/city/**',route=>failed?route.fulfill({status:503,contentType:'application/json',body:'{"error":"offline"}'}):route.fulfill({contentType:'application/json',body:JSON.stringify(fixture)}));
await page.goto(process.env.DALPH_DASHBOARD_URL || 'http://127.0.0.1:43597/');
await page.waitForFunction(()=>document.getElementById('connection').textContent.startsWith('Live'));
assert.equal(await page.locator('dalph-delivery-graph').evaluate(e=>e.projection.edges.length),9);
assert.equal(await page.locator('dalph-delivery-graph').evaluate(e=>e.shadowRoot.querySelector('details').open),false);
await page.locator('#frontier button').click();
assert.match(await page.locator('#facts').innerText(),/Join report text: work/);
assert.match(await page.locator('#facts').innerText(),/Format total lines: deliver/);
assert.match(await page.locator('#facts').innerText(),/Format item count: deliver/);
await page.locator('#grouping').check();
assert.equal(await page.locator('dalph-delivery-graph').evaluate(e=>e.projection.edges.length),18);
await page.locator('#grouping').uncheck();await page.locator('#fit').click();
failed=true;
await page.waitForFunction(()=>document.getElementById('connection').textContent.startsWith('Stale'),{},{timeout:20000});
assert.equal(await page.locator('dalph-delivery-graph').evaluate(e=>e.projection.tasks.length),9);
assert.ok((await page.locator('#error').innerText()).length>0);
assert.deepEqual(errors,[]);
console.log(JSON.stringify({passed:['fork/join edges','collapsed summary','selection prerequisites','grouping toggle','fit','stale retains graph'],errors}));
await page.setViewportSize({width:390,height:844});await page.waitForFunction(()=>document.documentElement.scrollWidth<=innerWidth,{},{timeout:3000});
await browser.close();
